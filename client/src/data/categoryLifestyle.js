export function getLifestyleLandingTiles(slug) {
  const cat = CATS[slug];
  if (!cat?.subGroups?.length) return [];
  const glyphs = TILE_GLYPHS[slug] || {};
  return cat.subGroups.map(({ group }) => ({
    label: group,
    filterValue: group,
    glyph: glyphs[group] || group.slice(0, 1),
  }));
}

